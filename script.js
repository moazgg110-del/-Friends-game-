function registerTouch(id,x,y){
  if(state.touches.has(id)||state.touches.size>=state.count)return;
  const r=$("#touchArea").getBoundingClientRect();
  const px=Math.max(8,Math.min(r.width-8,x-r.left));
  const py=Math.max(8,Math.min(r.height-8,y-r.top));
  const playerIndex=state.touches.size;
  state.touches.set(id,{x:px,y:py,playerIndex});
  const dot=document.createElement("div");
  dot.className="touch-point";dot.dataset.touch=String(id);
  dot.style.left=px+"px";dot.style.top=py+"px";dot.textContent=playerIndex+1;
  $("#touchArea").appendChild(dot);updateTouchStatus();
}
function removeTouch(id){
  state.touches.delete(id);
  const dot=$(`[data-touch="${CSS.escape(String(id))}"]`);if(dot)dot.remove();
  updateTouchStatus();
}
function getNextQuestion(){
  if(state.usedQuestions.size>=challenges.length) state.usedQuestions.clear();
  let available=[];
  for(let i=0;i<challenges.length;i++)if(!state.usedQuestions.has(i))available.push(i);
  const n=available[Math.floor(Math.random()*available.length)];
  state.usedQuestions.add(n);state.currentQuestion=n;return challenges[n];
}
